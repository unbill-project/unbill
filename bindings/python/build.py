"""Build a host-native, pip-installable package using the workspace UniFFI CLI."""

import argparse
import json
from pathlib import Path
import shutil
import subprocess
import sys


ROOT = Path(__file__).resolve().parents[2]


def validate_release_tag(version, tag):
    if tag != f"v{version}":
        raise ValueError(f"Release tag {tag!r} must match workspace version v{version}")


def run(*args):
    subprocess.run(args, cwd=ROOT, check=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--release", action="store_true")
    parser.add_argument("--expected-tag", help="Require a tag matching the workspace version")
    args = parser.parse_args()
    metadata = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--no-deps", "--format-version", "1"], cwd=ROOT
        )
    )
    crate = next(p for p in metadata["packages"] if p["name"] == "unbill-ffi")
    if args.expected_tag:
        try:
            validate_release_tag(crate["version"], args.expected_tag)
        except ValueError as error:
            parser.error(str(error))
    target = Path(metadata["target_directory"])
    profile = "release" if args.release else "debug"
    # Explicitly build the host even when .cargo/config or the environment sets
    # a cross-compilation target. Python must load a library for this host.
    rust_info = subprocess.check_output(["rustc", "-vV"], text=True)
    host = next(
        line.removeprefix("host: ")
        for line in rust_info.splitlines()
        if line.startswith("host: ")
    )
    flags = ["--release"] if args.release else []
    # The embedded license catalog inspects dependencies for all platforms.
    run("cargo", "fetch", "--locked")
    run(
        "cargo", "build", "--locked", "-p", "unbill-ffi", "--lib",
        "--bin", "uniffi-bindgen", "--target", host, *flags
    )
    native_dir = target / host / profile
    if sys.platform == "darwin":
        library_name = "libunbill_ffi.dylib"
    elif sys.platform == "win32":
        library_name = "unbill_ffi.dll"
    else:
        library_name = "libunbill_ffi.so"
    output = target / "python" / profile
    package = output / "unbill"
    package.mkdir(parents=True, exist_ok=True)
    generator = native_dir / ("uniffi-bindgen.exe" if sys.platform == "win32" else "uniffi-bindgen")
    run(str(generator), "generate", "--library", str(native_dir / library_name),
        "--language", "python", "--out-dir", str(package), "--no-format")
    shutil.copy2(native_dir / library_name, package / library_name)
    shutil.copy2(Path(__file__).with_name("README.md"), output / "README.md")
    for license_file in ["LICENSE-MIT", "LICENSE-APACHE"]:
        shutil.copy2(ROOT / license_file, output / license_file)
    (package / "__init__.py").write_text('"""Unbill console bindings generated by UniFFI."""\nfrom .unbill_ffi import *\n')
    (output / "pyproject.toml").write_text('''[build-system]
requires = ["setuptools>=77", "wheel"]
build-backend = "setuptools.build_meta"

[project]
name = "unbill"
version = VERSION
description = "Python bindings for the Unbill console"
readme = "README.md"
requires-python = ">=3.9"
license = "MIT OR Apache-2.0"
license-files = ["LICENSE-MIT", "LICENSE-APACHE"]

[project.urls]
Source = "https://github.com/unbill-project/unbill"

[tool.setuptools]
packages = ["unbill"]

[tool.setuptools.package-data]
unbill = ["*.dylib", "*.so", "*.dll"]
'''.replace("VERSION", repr(crate["version"])))
    # ctypes uses a platform library, but no CPython-specific extension ABI.
    (output / "setup.py").write_text('''import platform as host_platform
import sys

from setuptools import Distribution, setup
from wheel.bdist_wheel import bdist_wheel

class NativeDistribution(Distribution):
    def has_ext_modules(self):
        # Install into platlib at the wheel root so repair tools' relative
        # library paths survive installation. Rust supplies the native code.
        return True

class NativeWheel(bdist_wheel):
    def finalize_options(self):
        super().finalize_options()
        self.root_is_pure = False

    def get_tag(self):
        _, _, platform = super().get_tag()
        if sys.platform == "darwin":
            # Python.org interpreters may be universal2; the Rust library is
            # built for a single host architecture.
            platform = "_".join(platform.split("_")[:3]) + "_" + host_platform.machine()
        return "py3", "none", platform

setup(distclass=NativeDistribution, cmdclass={"bdist_wheel": NativeWheel})
''')
    print(f"Package ready: {output}")
    print(f"Install: python -m pip install {output}")


if __name__ == "__main__":
    main()
